// Regular User UI only: staff/auth icons retain their original styling.
import React, { forwardRef } from 'react';
import * as Icons from 'lucide-react-native';
import { useUserTheme } from './PremiumTheme';
import { darkIconColor } from './PremiumThemePrimitives';

const themedIcon = (Icon, displayName) => {
  const Component = forwardRef((props, ref) => {
    const { isDark } = useUserTheme();
    return <Icon {...props} ref={ref} color={isDark ? darkIconColor(props.color) : props.color} />;
  });
  Component.displayName = `Themed${displayName}`;
  return Component;
};
